SELECT
    D.CUIIO,
    R.CUATM,
    D.RIND,
    MR.ORDINE,
    CC.FULL_CODE,
    MAX(D.COL1)  AS  CUIIO_CAP1,
    MAX(D.COL2)  AS  IDNO_CAP1,
    MAX(D.COL33) AS DENUMIRE_CAP1,
    SUM(D.COL4)  AS COL1,
    SUM(D.COL5)  AS COL2,
    SUM(D.COL6)  AS COL3,
    SUM(D.COL7)  AS COL4,
    SUM(D.COL8)  AS COL5
   
    
    
  FROM
    CIS2.VW_DATA_ALL D
  
  INNER JOIN RENIM R ON R.CUIIO = D.CUIIO AND R.CUIIO_VERS = D.CUIIO_VERS
    INNER JOIN CIS2.MD_RIND MR ON MR.ID_MD = D.ID_MD
    INNER JOIN (SELECT 
C.ITEM_CODE CODUL,
C.NAME DENUMIRE,
C.A01 AS PRGS,
C.ITEM_PARENT,
C.ITEM_CODE_VERS,
C.ITEM_PATH FULL_CODE
FROM  CIS2.VW_CLS_CLASS_ITEM C INNER JOIN 
(
 SELECT 
 ITEM_CODE,
 MAX (ITEM_CODE_VERS) AS ITEM_CODE_VERS
 
 FROM  CIS2.VW_CLS_CLASS_ITEM
 
 WHERE 
 
 CLASS_CODE IN ('CUATM')
 
 GROUP BY
 ITEM_CODE ) CC ON C.ITEM_CODE = CC.ITEM_CODE AND C.ITEM_CODE_VERS = CC.ITEM_CODE_VERS) CC ON(D.CUATM = CC.CODUL)
    
    
    
 
 

  
  WHERE
-- D.CUIIO IN  (5694680) AND 
D.FORM = 73
AND D.PERIOADA = 2015

AND D.CAPITOL = 1196
--AND D.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%' 

--AND 
--(D.RIND LIKE '1000%' OR D.RIND LIKE '1300%') 

    GROUP BY 
   D.CUIIO,
    R.CUATM,
    D.RIND,
    MR.ORDINE,
    CC.FULL_CODE
    
    ORDER BY 
    CC.FULL_CODE,
    D.CUIIO,
    MR.ORDINE
     
